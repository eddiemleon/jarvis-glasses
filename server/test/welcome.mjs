// Saludo "Bienvenido de vuelta" tras 30 min sin hablar.
import assert from 'node:assert/strict';
import { rmSync } from 'node:fs';
rmSync('/tmp/jarvis-welcome', { recursive: true, force: true });
process.env.DATA_DIR = '/tmp/jarvis-welcome';
process.env.JARVIS_TZ = 'America/Puerto_Rico';
const { welcomeNote } = await import('../src/brain.js');
const { store } = await import('../src/store.js');
let pass = 0;
const ok = (n) => console.log('  ✓', n) || pass++;
console.log('Saludo de regreso');
const t0 = Date.parse('2026-11-04T23:40:00-04:00');
let w = welcomeNote(t0);
assert.match(w, /Bienvenido de vuelta, señor Leon\./);
assert.match(w, /primera vez/);
ok('primera conversación: lo recibe con "Bienvenido de vuelta, señor Leon."');
store.markTurn(t0, '2026-11-04', '23:40');
assert.equal(welcomeNote(t0 + 10 * 60_000), '');
ok('a los 10 minutos no repite el saludo (conversación seguida)');
const t1 = Date.parse('2026-11-05T09:10:00-04:00');
w = welcomeNote(t1);
assert.match(w, /Bienvenido de vuelta/);
assert.match(w, /10 horas/);
assert.match(w, /2026-11-04: primera 23:40, última 23:40/);
assert.match(w, /primera conversación de hoy/);
ok('al día siguiente: saludo + datos reales (ayer habló hasta las 23:40) para comentarlo');
store.markTurn(t1, '2026-11-05', '09:10');
assert.match(welcomeNote(t1 + 31 * 60_000), /31 minutos/);
ok('tras 31 minutos vuelve a saludar');
console.log(`\n${pass} pruebas OK`);
process.exit(0);
